'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const js=fs.readFileSync('librarian/librarian.js','utf8');
const css=fs.readFileSync('librarian/librarian.css','utf8');
new vm.Script(js,{filename:'librarian.js'});
assert(js.includes('Take a rest in our nice peaceful library'),'playful button');
assert(js.includes('const LETTERS=[\'A\',\'B\',\'C\',\'D\']'),'four letter choices');
