assert(js.includes('hero.x+dx*('),'direct frame-rate-independent movement');
assert(js.includes('function collide(')&&js.includes('if(b.hit'),'single-hit collision');
assert(js.includes('function defeated(')&&js.includes("pose('defeated')"),'stable defeat state');
assert(js.includes('function reveal(')&&css.includes('lib-learn-answer'),'learn panel');
